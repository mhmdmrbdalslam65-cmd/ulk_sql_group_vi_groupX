-- ULK SQL Group VI: Retail Sales Analytics
-- DBMS: PostgreSQL (pgAdmin 4)
-- Run this script first in a new database.

DROP TABLE IF EXISTS sale_items CASCADE;
DROP TABLE IF EXISTS sales CASCADE;
DROP TABLE IF EXISTS products CASCADE;
DROP TABLE IF EXISTS customers CASCADE;
DROP TABLE IF EXISTS employees CASCADE;
DROP TABLE IF EXISTS branches CASCADE;
DROP TABLE IF EXISTS regions CASCADE;

CREATE TABLE regions (
    region_id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    region_name    VARCHAR(80) NOT NULL UNIQUE
);

CREATE TABLE branches (
    branch_id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_name    VARCHAR(100) NOT NULL,
    region_id      INTEGER NOT NULL REFERENCES regions(region_id),
    city           VARCHAR(80) NOT NULL,
    UNIQUE (branch_name, region_id)
);

CREATE TABLE employees (
    employee_id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_name  VARCHAR(120) NOT NULL,
    job_title      VARCHAR(80) NOT NULL,
    branch_id      INTEGER NOT NULL REFERENCES branches(branch_id),
    manager_id     INTEGER REFERENCES employees(employee_id),
    hire_date      DATE NOT NULL,
    performance_score NUMERIC(5,2) CHECK (performance_score BETWEEN 0 AND 100)
);

CREATE TABLE customers (
    customer_id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_name  VARCHAR(120) NOT NULL,
    email          VARCHAR(150) UNIQUE,
    region_id      INTEGER NOT NULL REFERENCES regions(region_id),
    registration_date DATE NOT NULL
);

CREATE TABLE products (
    product_id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_name   VARCHAR(120) NOT NULL UNIQUE,
    category       VARCHAR(80) NOT NULL,
    unit_price     NUMERIC(12,2) NOT NULL CHECK (unit_price >= 0)
);

CREATE TABLE sales (
    sale_id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id    INTEGER NOT NULL REFERENCES customers(customer_id),
    branch_id      INTEGER NOT NULL REFERENCES branches(branch_id),
    employee_id    INTEGER NOT NULL REFERENCES employees(employee_id),
    sale_date      DATE NOT NULL,
    status         VARCHAR(20) NOT NULL DEFAULT 'COMPLETED'
                   CHECK (status IN ('COMPLETED','PENDING','CANCELLED'))
);

CREATE TABLE sale_items (
    sale_item_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_id        INTEGER NOT NULL REFERENCES sales(sale_id) ON DELETE CASCADE,
    product_id     INTEGER NOT NULL REFERENCES products(product_id),
    quantity       INTEGER NOT NULL CHECK (quantity > 0),
    unit_price     NUMERIC(12,2) NOT NULL CHECK (unit_price >= 0),
    UNIQUE (sale_id, product_id)
);

-- Helpful indexes for joins and date-based analysis.
CREATE INDEX idx_branches_region ON branches(region_id);
CREATE INDEX idx_customers_region ON customers(region_id);
CREATE INDEX idx_sales_customer ON sales(customer_id);
CREATE INDEX idx_sales_branch_date ON sales(branch_id, sale_date);
CREATE INDEX idx_sale_items_product ON sale_items(product_id);
